import type { Metadata } from 'next';
import { Geist, Geist_Mono } from 'next/font/google';
import { NextIntlClientProvider } from 'next-intl';
import { getLocale, getMessages } from 'next-intl/server';

import { AppShell } from '@/components/common/AppShell';
import { THEME_INIT_SCRIPT } from '@/lib/theme';

import './globals.css';

const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
});

const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
});

const DESCRIPTION = 'Recurring, streaming donations for verified NGOs on Stellar.';

export const metadata: Metadata = {
  // metadataBase is required for Next.js to resolve relative URLs used in
  // openGraph.images and twitter.images into fully-qualified URLs for crawlers.
  // Falls back to the local dev origin; set NEXT_PUBLIC_APP_URL in production.
  metadataBase: new URL(process.env.NEXT_PUBLIC_APP_URL ?? 'http://localhost:3001'),
  title: {
    default: 'StreamGive',
    // Child routes set just their own segment (e.g. "Explore NGOs") and
    // get this composed automatically, rather than repeating "StreamGive"
    // in every page's own metadata.
    template: '%s — StreamGive',
  },
  description: DESCRIPTION,
  // Browser toolbar / PWA chrome colour (matches the manifest and the logo).
  themeColor: [
    { media: '(prefers-color-scheme: light)', color: '#0d9488' },
    { media: '(prefers-color-scheme: dark)', color: '#0f172a' },
  ],
  openGraph: {
    title: 'StreamGive',
    description: DESCRIPTION,
    type: 'website',
    siteName: 'StreamGive',
    // /opengraph-image is generated by src/app/opengraph-image.tsx.
    images: [{ url: '/opengraph-image', width: 1200, height: 630, alt: 'StreamGive' }],
  },
  twitter: {
    // summary_large_image renders the OG image as a large card, not a thumbnail.
    card: 'summary_large_image',
    title: 'StreamGive',
    description: DESCRIPTION,
    images: ['/opengraph-image'],
  },
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Both come from src/i18n/request.ts (wired up via next.config.ts's
  // withNextIntl), which resolves the locale from the NEXT_LOCALE cookie.
  const locale = await getLocale();
  const messages = await getMessages();

  return (
    // suppressHydrationWarning: THEME_INIT_SCRIPT adds a `dark`/`light`
    // class here before React hydrates, which never matches the
    // server-rendered markup (the server doesn't know the client's
    // preference) — that mismatch is expected and this is the documented
    // way to silence the resulting warning without disabling it app-wide.
    <html lang={locale} suppressHydrationWarning>
      <head>
        {/* Must run synchronously, before paint, to avoid a flash of the
            wrong theme — see THEME_INIT_SCRIPT's own comment. */}
        <script dangerouslySetInnerHTML={{ __html: THEME_INIT_SCRIPT }} />
      </head>
      <body
        className={`${geistSans.variable} ${geistMono.variable} bg-white text-gray-900 antialiased dark:bg-gray-950 dark:text-gray-100`}
      >
        <NextIntlClientProvider locale={locale} messages={messages}>
          <AppShell>{children}</AppShell>
        </NextIntlClientProvider>
      </body>
    </html>
  );
}
